"""Build the coop mod into <game>/Mods/coop from the user's own install.

  python tools/build.py [--game "<install dir>"]

1. Stock scripts listed in patches.PATCHES are read from the user's fastfiles,
   patched at anchored points, and written as loose files (fs_game loose files
   override fastfile rawfiles in iw3sp).
2. Our own scripts in mod/ are copied verbatim.
3. The native proxy (native/build/d3d9.dll) is copied next to iw3sp.exe if built.
"""
import argparse
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import ffraw  # noqa: E402
import patches  # noqa: E402

DEFAULT_GAME = os.path.join(os.path.dirname(ROOT), 'Call of Duty 4-Modern Warfare')


def apply_edits(name, text, edits):
    for anchor, mode, payload in edits:
        hits = list(re.finditer(anchor, text, re.M))
        if len(hits) != 1:
            raise SystemExit('patch anchor for %s matched %d times: %r' % (name, len(hits), anchor))
        m = hits[0]
        if mode == 'after':
            text = text[:m.end()] + payload + text[m.end():]
        elif mode == 'before':
            text = text[:m.start()] + payload + text[m.start():]
        elif mode == 'replace':
            text = text[:m.start()] + payload + text[m.end():]
        else:
            raise SystemExit('bad mode ' + mode)
    return text


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--game', default=DEFAULT_GAME)
    ap.add_argument('--mod', default='coop')
    ap.add_argument('--also', default='', help='comma list of extra mod folder names to mirror into (tests)')
    a = ap.parse_args()
    exe = os.path.join(a.game, 'iw3sp.exe')
    if not os.path.isfile(exe):
        raise SystemExit('iw3sp.exe not found in ' + a.game)
    out = os.path.join(a.game, 'Mods', a.mod)
    os.makedirs(out, exist_ok=True)

    n = 0
    for p in patches.PATCHES:
        src = ffraw.find(a.game, p['file'], p.get('zones', ('common',))).decode('latin-1')
        src = apply_edits(p['file'], src, p['edits'])
        dst = os.path.join(out, p['file'])
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(dst, 'w', encoding='latin-1', newline='') as f:
            f.write(src)
        n += 1
    print('patched stock scripts:', n)

    mod_src = os.path.join(ROOT, 'mod')
    c = 0
    for dp, _, fs in os.walk(mod_src):
        for fn in fs:
            s = os.path.join(dp, fn)
            d = os.path.join(out, os.path.relpath(s, mod_src))
            os.makedirs(os.path.dirname(d), exist_ok=True)
            shutil.copyfile(s, d)
            c += 1
    print('copied mod files:', c)
    # custom character skins built by tools/skin/rebind.py + the OAT Linker: mod.ff plus loose .iwi textures
    skins = os.path.join(ROOT, 'build', 'skins')
    sff = os.path.join(skins, 'zone_out', 'mod.ff')
    if os.path.isfile(sff):
        shutil.copyfile(sff, os.path.join(out, 'mod.ff'))
        os.makedirs(os.path.join(out, 'images'), exist_ok=True)
        for fn in os.listdir(os.path.join(skins, 'images')):
            if fn.endswith('.iwi'):
                shutil.copyfile(os.path.join(skins, 'images', fn), os.path.join(out, 'images', fn))
        print('installed skins mod.ff')
    skin_list = []
    stxt = os.path.join(skins, 'skins.txt')
    if os.path.isfile(sff) and os.path.isfile(stxt):
        skin_list = [l.strip() for l in open(stxt) if l.strip()]
    # the game can only precache skins that are in its own pack: tell GSC and the launcher which ones
    with open(os.path.join(out, 'maps', '_coop_skins.gsc'), 'w', newline='\n') as f:
        f.write('// generated by tools/build.py from the skin pack (tools/skin/pack.py)\n\nlist()\n{\n\ts = [];\n')
        for m in skin_list:
            f.write('\ts[ s.size ] = "%s";\n' % m)
        f.write('\treturn s;\n}\n')
    with open(os.path.join(out, 'skins.txt'), 'w') as f:
        f.write('\n'.join(skin_list) + '\n')
    print('skins:', ', '.join(skin_list) or 'none')
    for extra in [x for x in a.also.split(',') if x]:
        dst = os.path.join(a.game, 'Mods', extra)
        shutil.copytree(out, dst, dirs_exist_ok=True, ignore=shutil.ignore_patterns('console.log'))
        print('mirrored to Mods/' + extra)

    dll = os.path.join(ROOT, 'native', 'build', 'd3d9.dll')
    if os.path.isfile(dll):
        try:
            shutil.copyfile(dll, os.path.join(a.game, 'd3d9.dll'))
            print('installed d3d9.dll proxy')
        except PermissionError:
            print('WARNING: d3d9.dll is in use (game running?) - proxy not updated')
    # One file for players: "CoD4 Coop.bat" = a small batch header that runs the rest of itself as PowerShell.
    # cmd reads "<# :" as a no-op label line; PowerShell reads everything up to "#>" as a comment.
    ps = open(os.path.join(ROOT, 'launcher', 'coop_launcher.ps1'), encoding='utf-8').read().replace('\r\n', '\n')
    header = (
        '<# :\n'
        '@echo off\n'
        'rem CoD4 Coop Campaign - double-click to host a game or join a friend. Everything is in this one file.\n'
        'set "COOP_GAMEDIR=%~dp0"\n'
        'set "COOP_SELF=%~f0"\n'
        'start "" powershell -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -Command '
        '"& ([scriptblock]::Create([IO.File]::ReadAllText($env:COOP_SELF)))"\n'
        'exit /b\n'
        '#>\n')
    # cmd wants CRLF; ASCII only so cmd never sees a BOM before "<# :"
    with open(os.path.join(a.game, 'CoD4 Coop.bat'), 'w', encoding='ascii', errors='replace', newline='\r\n') as f:
        f.write(header + ps)
    for old in ('Coop - Host.bat', 'Coop - Join.bat', 'coop_launcher.ps1'):  # earlier launcher layouts
        try:
            os.remove(os.path.join(a.game, old))
            print('removed old ' + old)
        except OSError:
            pass
    print('installed launcher: CoD4 Coop.bat')
    print('done ->', out)


if __name__ == '__main__':
    main()

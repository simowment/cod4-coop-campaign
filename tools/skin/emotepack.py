"""Custom emotes in the skin pack: what is staged, the zone lines, the music patch and the install.

Staged in <game>/coop_skins/work (by addemote.py):
  emotes/<id>.json          one per emote: display name, animtree slot, hold time, music
  emotes/sound/<file>       its song (mp3, or wav), streamed by the game from Mods/coop/sound/music/
  xanim/<slot node>         the retargeted animation
Installed into Mods/coop (and synced to friends by the launcher with the rest of the pack):
  mod.ff                    the xanims and the music aliases, next to the skins
  emotes.txt                name|node|hold ms|music alias|music file   (the launcher rebuilds the GSC from it)
  maps/_coop_emotes.gsc     generated: adds the emotes to the wheel
  sound/music/coopemote*    the songs

Why fixed slots: a script %anim must be a node of the stock generic_human animtree, so each custom emote
takes the xanim name of a node that no shipped fastfile has (nothing else in any level plays it). Music:
OAT cannot build IW3 sound aliases from source, so the pack carries copies of three streamed music aliases
from common.ff and this renames them (alias and file name, same length) to coopemote<N>_..._music.
No other module here: tools/build.py imports this without the game folder (release staging).
"""
import glob
import json
import os
import re
import shutil
import zlib

SLOTS = ['unarmed_waving', 'unarmed_waving_twitch', 'unarmed_waving_startidle', 'unarmed_waving_endidle']
# (stock streamed music alias in common.ff, its file in sound/music/)
TEMPLATES = [('russian_suspense_01_music', 'HGW_ICBM_tension2_v18.mp3'),
             ('cheat_chaplin_music', 'LC_silentmovie_special.mp3'),
             ('airplane_alt_maximum_music', 'HGW_airplane_alt_v2b.mp3')]
MUSIC_VOLUME = 0.9
MAX_MS = 30000          # an EM event carries at most 30 s (_coop_emote::ev_emote)
NAME_RE = r"^[A-Za-z0-9 _.!'-]{1,14}$"


def music_alias(m):
    """new alias name for music slot m: same length as the template's, ends in _music (= streamed song)"""
    n = len(TEMPLATES[m][0])
    return ('coopemote%d_' % (m + 1) + 'z' * 40)[:n - 6] + '_music'


def music_file(m, ext):
    n = len(TEMPLATES[m][1])
    return ('coopemote%d_' % (m + 1) + 'z' * 40)[:n - 4] + ext


def staged(work):
    """-> emote dicts sorted by slot"""
    d = os.path.join(work, 'emotes')
    out = []
    for f in glob.glob(os.path.join(d, '*.json')):
        try:
            e = json.load(open(f, encoding='utf-8'))
        except ValueError:
            continue
        if e.get('node') in SLOTS and os.path.isfile(os.path.join(work, 'xanim', e['node'])):
            out.append(e)
    return sorted(out, key=lambda e: SLOTS.index(e['node']))


def zone_lines(work):
    lines = []
    for e in staged(work):
        lines.append('xanim,%s' % e['node'])
        if e.get('music_slot') is not None:
            lines.append('sound,%s' % TEMPLATES[e['music_slot']][0])
    return lines


def patch_ff(ff, work):
    """rename the copied stock music aliases in the linked mod.ff to ours (same lengths: no offsets move)"""
    ems = [e for e in staged(work) if e.get('music_slot') is not None]
    if not ems:
        return
    raw = open(ff, 'rb').read()
    if raw[:8] != b'IWffu100':
        raise SystemExit('unexpected fastfile header in %s' % ff)
    z = bytearray(zlib.decompress(raw[12:]))
    for e in ems:
        m = e['music_slot']
        old_a, old_f = TEMPLATES[m]
        new_a, new_f = music_alias(m), e['music_file']
        for old, new in ((old_a, new_a), (old_f, new_f)):
            o, n = old.encode() + b'\0', new.encode() + b'\0'
            assert len(o) == len(n), (old, new)
            hits = [x.start() for x in re.finditer(re.escape(o), bytes(z))]
            if len(hits) != 1:
                raise SystemExit('music alias patch: %s found %d times in mod.ff' % (old, len(hits)))
            z[hits[0]:hits[0] + len(n)] = n
            if old == old_a:
                # snd_alias_t after the name: 5 pointers + sequence, then volMin, volMax
                vo = hits[0] + len(n) + 24
                vmin, vmax = (int.from_bytes(z[vo + k:vo + k + 4], 'little') for k in (0, 4))
                if vmin == vmax:
                    import struct
                    v = struct.unpack('<f', z[vo:vo + 4])[0]
                    if 0.1 < v <= 1.0:
                        z[vo:vo + 8] = struct.pack('<2f', MUSIC_VOLUME, MUSIC_VOLUME)
    open(ff, 'wb').write(raw[:12] + zlib.compress(bytes(z), 9))


def gsc_text(entries, who='the emote tools (tools/skin/addemote.py)'):
    s = '// generated by %s: the custom emotes of the pack\n#using_animtree( "generic_human" );\n\nadd_all()\n{\n' % who
    for e in entries:
        snd = '"%s"' % e['music'] if e.get('music') else 'undefined'
        s += '\tmaps\\_coop_emote::add_custom( "%s", %d, %s, %%%s );\n' % (e['name'], e['hold_ms'], snd, e['node'])
    return s + '}\n'


def txt_lines(entries):
    return ''.join('%s|%s|%d|%s|%s\n' % (e['name'], e['node'], e['hold_ms'], e.get('music') or '-',
                                         e.get('music_file') or '-') for e in entries)


def install(mod, work, pack_ok=True):
    """write the GSC list, emotes.txt and the songs into the installed mod (pack_ok: mod.ff has them)"""
    ems = staged(work) if pack_ok else []
    snd_dst = os.path.join(mod, 'sound', 'music')
    for old in glob.glob(os.path.join(snd_dst, 'coopemote*')):
        os.remove(old)
    for e in ems:
        if e.get('music_file'):
            src = os.path.join(work, 'emotes', 'sound', e['music_file'])
            if os.path.isfile(src):
                os.makedirs(snd_dst, exist_ok=True)
                shutil.copyfile(src, os.path.join(snd_dst, e['music_file']))
            else:
                e['music'] = e['music_file'] = None
    os.makedirs(os.path.join(mod, 'maps'), exist_ok=True)
    with open(os.path.join(mod, 'maps', '_coop_emotes.gsc'), 'w', newline='\n') as f:
        f.write(gsc_text(ems))
    txt = os.path.join(mod, 'emotes.txt')
    if ems:
        with open(txt, 'w', encoding='utf-8', newline='\n') as f:
            f.write(txt_lines(ems))
    elif os.path.isfile(txt):
        os.remove(txt)
    return ems

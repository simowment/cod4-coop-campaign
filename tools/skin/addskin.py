"""One-step skin management (what the launcher's Skins tab runs).

  python addskin.py add <model file> <name> [--flip] [--layers preset.json]
  python addskin.py remove <name>
  python addskin.py list

add:    rigged or not (auto-rig), GLB / glTF / DAE / OBJ / FBX (FBX needs Blender) -> converted onto the
        CoD4 skeleton, preview at coop_skins/work/previews/<name>.png, skin pack rebuilt and installed
remove: drops the skin from the pack and reinstalls
Progress goes to stdout line by line; the last line is "OK ..." or "ERROR ...".
"""
import glob
import os
import shutil
import sys
import traceback

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import skinenv  # noqa: E402

MOD = os.path.join(skinenv.GAME, 'Mods', 'coop')


def staged():
    xd = os.path.join(skinenv.WORK, 'xmodel')
    return sorted(f[:-5] for f in os.listdir(xd) if f.endswith('.skin')) if os.path.isdir(xd) else []


def install():
    """Copy the linked pack, textures and the skin list into Mods/coop (what tools/build.py also does)."""
    skins = staged()
    ff = os.path.join(skinenv.WORK, 'zone_out', 'mod.ff')
    img_dst = os.path.join(MOD, 'images')
    for old in glob.glob(os.path.join(img_dst, 'coop_*_col.iwi')):
        os.remove(old)
    if skins and os.path.isfile(ff):
        shutil.copyfile(ff, os.path.join(MOD, 'mod.ff'))
        os.makedirs(img_dst, exist_ok=True)
        for f in glob.glob(os.path.join(skinenv.WORK, 'images', '*.iwi')):
            shutil.copyfile(f, os.path.join(img_dst, os.path.basename(f)))
    elif os.path.isfile(os.path.join(MOD, 'mod.ff')):
        os.remove(os.path.join(MOD, 'mod.ff'))
    with open(os.path.join(MOD, 'maps', '_coop_skins.gsc'), 'w', newline='\n') as f:
        f.write('// generated by the skin tools\n\nlist()\n{\n\ts = [];\n')
        for m in skins:
            f.write('\ts[ s.size ] = "%s";\n' % m)
        f.write('\treturn s;\n}\n')
    with open(os.path.join(MOD, 'skins.txt'), 'w') as f:
        f.write('\n'.join(skins) + '\n')


def repack():
    import pack
    if staged():
        pack.main()
    install()


def remove_staged(model):
    w = skinenv.WORK
    name = model[len('coop_'):]
    pats = [os.path.join(w, 'xmodel', model + '.*'), os.path.join(w, 'model_export', model + '.glb'),
            os.path.join(w, 'materials', 'mc', 'mtl_coop_%s_*.json' % name), os.path.join(w, 'images', 'coop_%s_*_col.*' % name),
            os.path.join(w, 'previews', model + '.png')]
    for p in pats:
        for f in glob.glob(p):
            os.remove(f)


def main():
    args = sys.argv[1:]
    if not args:
        print(__doc__)
        return
    cmd = args[0]
    try:
        if cmd == 'list':
            for m in staged():
                print(m)
            return
        if cmd == 'add':
            import argparse
            ap = argparse.ArgumentParser()
            ap.add_argument('file')
            ap.add_argument('name')
            ap.add_argument('--flip', action='store_true')
            ap.add_argument('--layers')
            a = ap.parse_args(args[1:])
            import rebind
            os.makedirs(os.path.join(skinenv.WORK, 'previews'), exist_ok=True)
            name = rebind.re.sub(r'[^a-z0-9_]', '_', a.name.lower()).strip('_') or 'skin'
            model = 'coop_' + name
            remove_staged(model)
            skinenv.say('converting %s ...' % os.path.basename(a.file))
            preview = os.path.join(skinenv.WORK, 'previews', model + '.png')
            rebind.convert(a.file, name, out=skinenv.WORK, preview=preview, layers=a.layers, flip=a.flip)
            skinenv.say('building the skin pack ...')
            repack()
            print('OK %s preview=%s' % (model, preview), flush=True)
            return
        if cmd == 'remove':
            model = args[1] if args[1].startswith('coop_') else 'coop_' + args[1]
            remove_staged(model)
            repack()
            print('OK removed %s' % model, flush=True)
            return
        print('ERROR unknown command ' + cmd)
    except SystemExit as e:
        print('ERROR %s' % e, flush=True)
        sys.exit(1)
    except Exception as e:  # noqa: BLE001
        traceback.print_exc()
        print('ERROR %s' % e, flush=True)
        sys.exit(1)


if __name__ == '__main__':
    main()
